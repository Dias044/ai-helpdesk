def gen_dataset(n_per_class=140, seed=7):
    rnd = random.Random(seed); X, y = [], []
    for c in CATEGORIES:
        for _ in range(n_per_class):
            core = rnd.choice(CORES[c]).format(s=rnd.choice(SUBJ), d=rnd.choice(DAY))
            t = rnd.choice(OPEN) + core + rnd.choice(["", "?", ".", ""]) + rnd.choice(TAIL)
            if rnd.random() < 0.2:
                other = rnd.choice([k for k in CATEGORIES if k != c]); t += " " + rnd.choice(CROSS[other])
            if rnd.random() < 0.3: t = t.lower()
            X.append(t.strip()); y.append(c)
    return X, y

